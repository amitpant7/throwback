#!/usr/bin/env python3
"""Writes the home-screen shortcut icons' foreground layers (adaptive-icon vector drawables, 108 dp)
from the logo's mark, design/logo/logo-mark-transparent.svg, at the launcher icon's size and place.
The mark's paths are copied from that file; only the ring, arrow and dots take the variant's colour.
Run from the repository root after changing the logo: python3 tools/icons/shortcut_mark.py"""
import re

SVG = 'design/logo/logo-mark-transparent.svg'
OUT = 'app/src/main/res/drawable/'
SCALE = 0.347                     # dp per SVG unit: the launcher foreground's size (measured)
SHIFT = 54 - 128 * SCALE          # the SVG's centre (128) on the 108 dp layer's centre
VARIANTS = {  # file: (ring colour, what it is for)
    'ui_shortcut_mark': ('#F5FFF9', 'on the app colour and on dark'),
    'ui_shortcut_mark_light': ('#2F7D57', 'on light: a green ring, since a white one would vanish'),
}

svg = open(SVG).read()
paths = {d: (fill, rule) for d, fill, rule in re.findall(r'<path d="([^"]+)" fill="(#[0-9A-F]{6})"( fill-rule="evenodd")?', svg)}
strokes = re.findall(r'<path d="([^"]+)" fill="none" stroke="#F5FFF9" stroke-width="12"', svg)
dots = re.findall(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)" fill="#F5FFF9"', svg)
assert len(paths) == 2 and len(strokes) == 2 and len(dots) == 2, 'the mark changed: update this script'


def circle(cx, cy, r):
    cx, cy, r = float(cx), float(cy), float(r)
    return f'M{cx - r:.1f},{cy}a{r},{r} 0 1,0 {2 * r:.1f},0a{r},{r} 0 1,0 {-2 * r:.1f},0z'


def gradient(cx, cy, r, stops):
    items = ''.join(f'\n                    <item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    return f'''
            <aapt:attr name="android:fillColor">
                <gradient android:type="radial" android:centerX="{cx}" android:centerY="{cy}"
                    android:gradientRadius="{r}">{items}
                </gradient>
            </aapt:attr>'''


for name, (ring, why) in VARIANTS.items():
    body = [
        # The portal: the SVG's radial gradients in user space (bounding box 61..195 for the portal).
        f'<path android:pathData="{circle(128, 128, 67)}">{gradient(121.3, 117.3, 93.8, [(0, "#FF1F5446"), (0.55, "#FF0E2A23"), (1, "#FF06120E")])}\n        </path>',
        f'<path android:pathData="{circle(128, 128, 38)}">{gradient(128, 128, 38, [(0, "#808FD1AD"), (1, "#008FD1AD")])}\n        </path>',
    ]
    for d, (fill, rule) in paths.items():  # the sparkle and the figure keep their own colours
        # The figure's path is long (lint: VectorPath); fine for an icon drawn once and cached.
        extra = ' android:fillType="evenOdd" tools:ignore="VectorPath"' if rule else ''
        body.append(f'<path android:fillColor="{fill}"{extra}\n            android:pathData="{d}" />')
    for d in strokes:
        body.append(f'<path android:strokeColor="{ring}" android:strokeWidth="12" android:strokeLineCap="round"\n            android:strokeLineJoin="round" android:pathData="{d}" />')
    for cx, cy, r in dots:
        body.append(f'<path android:fillColor="{ring}" android:pathData="{circle(cx, cy, r)}" />')
    inner = '\n        '.join(body)
    open(OUT + name + '.xml', 'w').write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icons/shortcut_mark.py from design/logo/logo-mark-transparent.svg: don't edit.
     The logo's mark as a shortcut icon's foreground layer, {why}. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    xmlns:tools="http://schemas.android.com/tools"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{SHIFT:.3f}" android:translateY="{SHIFT:.3f}" android:scaleX="{SCALE}" android:scaleY="{SCALE}">
        {inner}
    </group>
</vector>
''')
    print('wrote', OUT + name + '.xml')
